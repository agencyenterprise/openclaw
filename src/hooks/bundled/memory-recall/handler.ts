/**
 * Memory Recall hook — SOUL Article 8 / Derivation (retrieve before you plan).
 * Implements SOUL Derivation clause: retrieve before planning (automatic)
 *
 * A `before_prompt_build` core hook (the awaited prompt-assembly hook; internal
 * message hooks are fire-and-forget and cannot touch the prompt) takes the
 * inbound message identity and text from the typed `ctx.inboundMessage` the
 * reply pipeline attaches, runs Hindsight recall and the markdown memory search
 * in parallel, and prepends the merged hits to the prompt. `message:received`
 * stashes human messages per thread so the thread's previous human message can
 * join the query, and remembers bot-authored ids. Every retrieval leaves one
 * line in `<workspace>/state/retrieval_log.jsonl`, once per session + message id.
 *
 * The core hook is registered when this module loads and re-registered with
 * the live config on `gateway:startup`; core hooks survive plugin registry
 * re-activation.
 */

