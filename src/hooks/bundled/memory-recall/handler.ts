const log = createSubsystemLogger("hooks/memory-recall");

export const MEMORY_RECALL_PLUGIN_ID = "fractal-memory-recall";
export const MEMORY_RECALL_HOOK_NAME = "before_prompt_build";
/** Hindsight candidates requested per turn; `maxItems` caps what gets injected. */
export const HINDSIGHT_MAX_RESULTS = 6;
/**
 * Margin over the retrieval deadline before the hook runner fails the hook open.
 * The runner budget for our `before_prompt_build` registration is derived as
 * `timeoutMs + this`, so raising the hook's timeout raises the runner budget with it
 * instead of the hook dying at a budget that no longer matches its own deadline.
 */
export const PROMPT_BUILD_TIMEOUT_MARGIN_MS = 1_500;
/**
 * Deadline for the evidence write, shrunk to whatever is left of the runner budget
 * once retrieval has spent its share, so the write can never hold the turn past it.
 */
export const LOG_WRITE_TIMEOUT_MS = 3_000;
const COMPLETED_TURN_CACHE_SIZE = 2000;
const HUMAN_TRIGGER = "user";
/** Providers whose prompts are generated by the gateway, not typed by a human. */
const NON_HUMAN_PROVIDERS = new Set(["heartbeat", "cron-event", "exec-event"]);

type PromptBuildHandler = PluginHookHandlerMap[typeof MEMORY_RECALL_HOOK_NAME];
type PromptBuildResult = Awaited<ReturnType<PromptBuildHandler>>;

export type RetrieverFactoryParams = {
  cfg: OpenClawConfig;
  agentId: string;
  sessionKey: string;
  recall: MemoryRecallConfig;
};

export type MemoryRecallDeps = {
  stash: InboundMessageStash;
  resolveConfig: () => { cfg: OpenClawConfig | null; recall: MemoryRecallConfig };
  createRetrievers: (params: RetrieverFactoryParams) => MemoryRetrievers;
  resolveWorkspaceDir: (sessionKey: string, hint?: string) => string;
  /** Throttled: degraded retrieval, skipped injection. */
  warn: (message: string) => void;
  /** Unthrottled: lost evidence (a retrieval log line could not be written). */
  logError: (message: string) => void;
  /** Timeout the hook runner enforces on the registered core hook, when known. */
  resolveOuterTimeoutMs?: () => number | undefined;
  now?: () => Date;
};

function readString(value: unknown): string | undefined {
  if (typeof value === "number") {
    return String(value);
  }
  return typeof value === "string" && value.trim().length > 0 ? value : undefined;
}

export function createDefaultRetrievers(params: RetrieverFactoryParams): MemoryRetrievers {
  const { cfg, agentId, sessionKey, recall } = params;
  return {
    recallHindsight: async (query, signal) => {
      const hindsightConfig = resolveHindsightConfig(cfg);
      if (!hindsightConfig.enabled) {
        return {
          results: [],
          fetched: 0,
          ms: 0,
          error: "hindsight disabled in memory-core config",
        };
      }
      return recallHindsightMemoriesSafely({
        config: {
          ...hindsightConfig,
          budget: "mid",
          maxResults: HINDSIGHT_MAX_RESULTS,
          timeoutMs: recall.timeoutMs,
        },
        query,
        maxResults: HINDSIGHT_MAX_RESULTS,
        cancellation: { callerSignal: signal },
      });
    },
    searchMarkdown: async (query, signal) => {
      const { manager, error } = await getActiveMemorySearchManager({ cfg, agentId });
      if (!manager) {
        throw new Error(error ?? "memory search manager unavailable");
      }
      return manager.search(query, {
        maxResults: recall.maxItems,
        sessionKey,
        sources: ["memory"],
        signal,
      });
    },
  };
}

/** Stash human messages per thread; remember bot-authored ids so their turns are skipped. */
export function recordInboundMessage(stash: InboundMessageStash, event: InternalHookEvent): void {
  const ctx = event.context as MessageReceivedHookContext;
  if (!ctx.messageId || !ctx.content) {
    return;
  }
  const metadata = (ctx.metadata ?? {}) as {
    provider?: unknown;
    threadId?: unknown;
    senderIsBot?: unknown;
  };
  if (metadata.senderIsBot === true) {
    stash.rejectBotMessage(event.sessionKey, ctx.messageId);
    return;
  }
  const provider = readString(metadata.provider);
  if (provider && NON_HUMAN_PROVIDERS.has(provider)) {
    return;
  }
  stash.record(event.sessionKey, {
    messageId: ctx.messageId,
    text: ctx.content,
    threadId: readString(metadata.threadId) ?? extractSlackThreadTsFromSessionKey(event.sessionKey),
  });
}

function failedOutcome(error: string): RetrievalOutcome {
  return {
    items: [],
    hindsightHits: 0,
    markdownHits: 0,
    ms: 0,
    failedSources: ["hindsight", "markdown"],
    error,
  };
}

async function withDeadline<T>(task: Promise<T>, timeoutMs: number, label: string): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const deadline = new Promise<never>((_resolve, reject) => {
    timer = setTimeout(
      () => reject(new Error(`${label} timed out after ${timeoutMs}ms`)),
      timeoutMs,
    );
  });
  try {
    return await Promise.race([task, deadline]);
  } finally {
    clearTimeout(timer);
  }
}

type InboundTurn = PluginHookInboundMessageContext & { messageId: string; text: string };

/** The `before_prompt_build` handler: retrieve, inject, log — never throw. */
export function createPromptBuildHandler(deps: MemoryRecallDeps): PromptBuildHandler {
  const now = deps.now ?? (() => new Date());
  const completedTurns = new LruMap<string, string | undefined>(COMPLETED_TURN_CACHE_SIZE);
  const inFlightTurns = new Map<string, Promise<string | undefined>>();

  const toResult = (block: string | undefined): PromptBuildResult =>
    block ? { prependContext: block } : undefined;

  /** Never let retrieval outlive the deadline the hook runner enforces on us. */
  const resolveRetrievalTimeoutMs = (recall: MemoryRecallConfig): number => {
    const outer = deps.resolveOuterTimeoutMs?.();
    return outer === undefined
      ? recall.timeoutMs
      : Math.max(1, Math.min(recall.timeoutMs, outer - PROMPT_BUILD_TIMEOUT_MARGIN_MS));
  };

  /** The evidence write gets the full deadline only if the runner budget still allows it. */
  const resolveLogWriteTimeoutMs = (retrievalMs: number): number => {
    const outer = deps.resolveOuterTimeoutMs?.();
    return outer === undefined
      ? LOG_WRITE_TIMEOUT_MS
      : Math.max(1, Math.min(LOG_WRITE_TIMEOUT_MS, outer - retrievalMs));
  };

  const retrieve = async (params: {
    cfg: OpenClawConfig;
    recall: MemoryRecallConfig;
    sessionKey: string;
    agentId: string;
    query: string;
  }): Promise<RetrievalOutcome> => {
    const { cfg, recall, sessionKey, agentId } = params;
    let retrievers: MemoryRetrievers;
    try {
      retrievers = deps.createRetrievers({ cfg, recall, sessionKey, agentId });
    } catch (err) {
      return failedOutcome(`retrievers unavailable: ${formatErrorMessage(err)}`);
    }
    return retrieveMemory({
      query: params.query,
      maxItems: recall.maxItems,
      timeoutMs: resolveRetrievalTimeoutMs(recall),
      retrievers,
    });
  };

  const runTurn = async (params: {
    cfg: OpenClawConfig;
    recall: MemoryRecallConfig;
    ctx: PluginHookAgentContext;
    sessionKey: string;
    inbound: InboundTurn;
    query: string;
    cacheKey: string;
  }): Promise<string | undefined> => {
    const { cfg, recall, ctx, sessionKey, inbound, query } = params;
    const agentId = ctx.agentId ?? resolveAgentIdFromSessionKey(sessionKey);
    const outcome = await retrieve({ cfg, recall, sessionKey, agentId, query });
    if (outcome.error) {
      deps.warn(`memory-recall: ${outcome.error}`);
    }
    const block = buildRetrievedMemoryBlock(outcome.items, recall);
    const entry = buildRetrievalLogEntry({
      now: now(),
      sessionKey,
      messageId: inbound.messageId,
      channel: inbound.channel ?? extractSlackChannelFromSessionKey(sessionKey) ?? ctx.chatId,
      threadTs: inbound.threadTs ?? extractSlackThreadTsFromSessionKey(sessionKey),
      query,
      outcome,
      injectedChars: block?.length ?? 0,
    });
    try {
      const write = appendRetrievalLogEntry(
        deps.resolveWorkspaceDir(sessionKey, ctx.workspaceDir),
        entry,
      );
      write.catch(() => undefined);
      await withDeadline(write, resolveLogWriteTimeoutMs(outcome.ms), "retrieval log write");
      completedTurns.set(params.cacheKey, block);
    } catch (err) {
      // Policy: the block still ships — losing one evidence line must not degrade
      // the answer. The turn stays uncached so a retry writes the missing line.
      deps.logError(`memory-recall: retrieval log write failed: ${formatErrorMessage(err)}`);
    }
    return block;
  };

  const resolveInboundTurn = (ctx: PluginHookAgentContext): InboundTurn | undefined => {
    const inbound = ctx.inboundMessage;
    if (!inbound?.messageId || inbound.senderIsBot === true) {
      return undefined;
    }
    return { ...inbound, messageId: inbound.messageId, text: inbound.text ?? "" };
  };

  const recallForTurn = async (ctx: PluginHookAgentContext): Promise<PromptBuildResult> => {
    const { cfg, recall } = deps.resolveConfig();
    if (!recall.enabled) {
      return undefined;
    }
    if (ctx.trigger && ctx.trigger !== HUMAN_TRIGGER) {
      return undefined;
    }
    if (ctx.messageProvider && NON_HUMAN_PROVIDERS.has(ctx.messageProvider)) {
      return undefined;
    }
    const sessionKey = ctx.sessionKey;
    if (!cfg || !sessionKey) {
      const reason = cfg
        ? "no session key on the prompt-build context"
        : "runtime config snapshot unavailable";
      deps.warn(`memory-recall: ${reason}; nothing retrieved`);
      return undefined;
    }
    const inbound = resolveInboundTurn(ctx);
    if (!inbound || deps.stash.isRejectedBotMessage(sessionKey, inbound.messageId)) {
      return undefined;
    }
    if (inbound.text.trim().length < recall.minMessageChars) {
      return undefined;
    }
    const threadContext = deps.stash.findThreadContext(sessionKey, {
      messageId: inbound.messageId,
      text: inbound.text,
      threadId: inbound.threadTs,
    });
    const query = buildRetrievalQuery(inbound.text, threadContext);
    // Same message id but a different query (edited text, thread context that
    // arrived later) is a different retrieval.
    const key = turnKey(sessionKey, `${inbound.messageId}#${digestQuery(query)}`);
    if (completedTurns.has(key)) {
      return toResult(completedTurns.get(key));
    }
    let inFlight = inFlightTurns.get(key);
    if (!inFlight) {
      inFlight = runTurn({ cfg, recall, ctx, sessionKey, inbound, query, cacheKey: key }).finally(
        () => {
          inFlightTurns.delete(key);
        },
      );
      inFlightTurns.set(key, inFlight);
    }
    return toResult(await inFlight);
  };

  return async (_event, ctx) => {
    try {
      return await recallForTurn(ctx);
    } catch (err) {
      deps.warn(`memory-recall: retrieval failed; nothing injected: ${formatErrorMessage(err)}`);
      return undefined;
    }
  };
}

export type MemoryRecallHook = {
  /** Registers (or re-registers) the prompt-build core hook with the current timeout. */
  register: () => void;
  /** Internal hook: re-registers on gateway startup, stashes human messages on receipt. */
  internalHook: HookHandler;
};

export function createMemoryRecallHook(deps: MemoryRecallDeps): MemoryRecallHook {
  let registeredTimeoutMs: number | undefined;
  const promptBuild = createPromptBuildHandler({
    ...deps,
    resolveOuterTimeoutMs: () => registeredTimeoutMs,
  });
  const register = () => {
    registeredTimeoutMs = deps.resolveConfig().recall.timeoutMs + PROMPT_BUILD_TIMEOUT_MARGIN_MS;
    registerCoreHook({
      pluginId: MEMORY_RECALL_PLUGIN_ID,
      hookName: MEMORY_RECALL_HOOK_NAME,
      handler: promptBuild,
      timeoutMs: registeredTimeoutMs,
    });
  };
  const internalHook: HookHandler = (event) => {
    if (event.type === "gateway" && event.action === "startup") {
      try {
        register();
      } catch (err) {
        log.error(`memory-recall: re-registration at startup failed: ${formatErrorMessage(err)}`);
      }
      if (hasCoreHook(MEMORY_RECALL_PLUGIN_ID, MEMORY_RECALL_HOOK_NAME)) {
        log.info("memory-recall: before_prompt_build retrieval is registered");
      } else {
        log.error(
          "memory-recall: before_prompt_build retrieval is NOT registered; nothing retrieved",
        );
      }
      return;
    }
    if (event.type === "message" && event.action === "received") {
      recordInboundMessage(deps.stash, event);
    }
  };
  return { register, internalHook };
}

const memoryRecallHook = createMemoryRecallHook({
  stash: new InboundMessageStash(),
  resolveConfig: () => {
    const cfg = getRuntimeConfigSnapshot();
    return { cfg, recall: resolveMemoryRecallConfig(cfg) };
  },
  createRetrievers: createDefaultRetrievers,
  resolveWorkspaceDir: (sessionKey, hint) => hint ?? resolveHookWorkspaceDir(sessionKey),
  warn: createThrottledWarn((message) => log.warn(message)),
  logError: (message) => log.error(message),
});

try {
  memoryRecallHook.register();
} catch (err) {
  // Never let a config failure at import time break gateway startup; the
  // gateway:startup event re-registers with the live config.
  log.error(`memory-recall: registration at load failed: ${formatErrorMessage(err)}`);
}

export default memoryRecallHook.internalHook;
